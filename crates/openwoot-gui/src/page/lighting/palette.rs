use openwoot_protocol::lighting::{KeyColors, Rgb};

use super::color::BLACK;

const ROWS: usize = 6;
const SIXTY_COLUMNS: usize = 14;
const EIGHTY_COLUMNS: usize = 17;

type Grid = [&'static str; ROWS];

pub(super) struct Preset {
    pub(super) name: &'static str,
    full: Grid,
    sixty: Option<Grid>,
    eighty: Option<Grid>,
}

impl Preset {
    pub(super) fn key_colors(&self, rows: usize, columns: usize) -> KeyColors {
        let grid: Vec<Vec<Rgb>> = self.grid(columns).iter().map(|line| parse(line)).collect();
        let mut colors = KeyColors::new();
        for row in 0..rows {
            for column in 0..columns {
                let color = grid
                    .get(row)
                    .and_then(|line| line.get(column))
                    .copied()
                    .unwrap_or(BLACK);
                if colors.push(color).is_err() {
                    return colors;
                }
            }
        }
        colors
    }

    const fn grid(&self, columns: usize) -> &Grid {
        match (columns, &self.sixty, &self.eighty) {
            (SIXTY_COLUMNS, Some(grid), _) | (EIGHTY_COLUMNS, _, Some(grid)) => grid,
            _ => &self.full,
        }
    }
}

