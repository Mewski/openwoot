fn parse(line: &str) -> Vec<Rgb> {
    line.split_ascii_whitespace()
        .map(|token| u32::from_str_radix(token, 16).map_or(BLACK, rgb_of_hex))
        .collect()
}

const fn rgb_of_hex(value: u32) -> Rgb {
    let [_, red, green, blue] = value.to_be_bytes();
    Rgb { red, green, blue }
}

#[cfg(test)]
mod tests {
    use super::*;

    const STOCK_COLUMNS: usize = 21;
    const HEX_DIGITS: usize = 6;

    fn grids() -> impl Iterator<Item = &'static Grid> {
        PRESETS.iter().flat_map(|preset| {
            [
                Some(&preset.full),
                preset.sixty.as_ref(),
                preset.eighty.as_ref(),
            ]
            .into_iter()
            .flatten()
        })
    }

    #[test]
    fn every_arrangement_holds_six_rows_of_twenty_one_colours() {
        for grid in grids() {
            for line in grid {
                let tokens: Vec<&str> = line.split_ascii_whitespace().collect();
                assert_eq!(tokens.len(), STOCK_COLUMNS, "{line}");
                for token in tokens {
                    assert_eq!(token.len(), HEX_DIGITS, "{token}");
                    assert!(u32::from_str_radix(token, 16).is_ok(), "{token}");
                }
            }
        }
    }

    #[test]
    fn the_colours_follow_the_key_matrix() {
        let seawave = PRESETS
            .iter()
            .find(|preset| preset.name == "Seawave")
            .unwrap();
        let colors = seawave.key_colors(6, 17);
        assert_eq!(colors.len(), 6 * 17);
        let blue = Rgb {
            red: 0,
            green: 0,
            blue: 255,
        };
        let sky = Rgb {
            red: 0,
            green: 0x77,
            blue: 255,
        };
        assert_eq!(colors[0], blue);
        assert_eq!(colors[4], blue);
        assert_eq!(colors[5], sky);
        assert_eq!(colors[17 + 5], sky);
    }

    #[test]
    fn a_matrix_of_the_width_of_a_stock_arrangement_gets_that_arrangement() {
        let rainbow = PRESETS
            .iter()
            .find(|preset| preset.name == "Rainbow")
            .unwrap();
        assert_eq!(rainbow.key_colors(6, 14)[0], BLACK);
        assert_ne!(rainbow.key_colors(6, 17)[0], BLACK);
        let alternator = PRESETS
            .iter()
            .find(|preset| preset.name == "Alternator")
            .unwrap();
        assert_eq!(alternator.grid(17), alternator.eighty.as_ref().unwrap());
        assert_eq!(alternator.grid(14), &alternator.full);
        assert_eq!(alternator.grid(21), &alternator.full);
    }

    #[test]
    fn small_and_large_matrices_get_black_outside_the_arrangement() {
        let inferno = PRESETS
            .iter()
            .find(|preset| preset.name == "Inferno")
            .unwrap();
        let wide = inferno.key_colors(5, 22);
        assert_eq!(wide.len(), 5 * 22);
        assert_ne!(wide[20], BLACK);
        assert_eq!(wide[21], BLACK);
        let tall = inferno.key_colors(7, 18);
        assert_eq!(tall.len(), 7 * 18);
        assert_ne!(tall[5 * 18], BLACK);
        assert_eq!(tall[6 * 18], BLACK);
        assert_eq!(inferno.key_colors(0, 17).len(), 0);
    }
}
